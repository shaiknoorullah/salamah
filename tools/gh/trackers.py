"""Tracker helpers for scheduled jobs: file issues without duplicates, report the nightly run."""

import argparse
import os
import sys
from collections.abc import Sequence

from tools.gh.api import GitHub

FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
READY = "All sub-issues closed"


def find_milestone(gh: GitHub, title: str) -> int:
    for m in gh.paginate(f"/repos/{gh.repo}/milestones?state=open"):
        if m["title"] == title:
            return m["number"]
    raise LookupError(f"no open milestone {title!r}")


def _open_issues(gh: GitHub, query: str = "") -> list[dict]:
    path = f"/repos/{gh.repo}/issues?state=open{query}"
    return [i for i in gh.paginate(path) if "pull_request" not in i]


def file_issue(gh: GitHub, title: str, body: str, labels: Sequence[str], milestone: str) -> int:
    for issue in _open_issues(gh, "&labels=agent-filed"):
        if issue["title"] == title:
            return issue["number"]
    payload = {
        "title": title,
        "body": body + FOOTER,
        "labels": list(labels),
        "milestone": find_milestone(gh, milestone),
    }
    return gh.request("POST", f"/repos/{gh.repo}/issues", payload)["number"]


def ready_trackers(gh: GitHub) -> list[int]:
    out = []
    for issue in _open_issues(gh):
        subs = gh.request("GET", f"/repos/{gh.repo}/issues/{issue['number']}/sub_issues") or []
        if subs and all(s["state"] == "closed" for s in subs):
            out.append(issue["number"])
    return out


def _comment(gh: GitHub, issue: int, text: str) -> None:
    gh.request("POST", f"/repos/{gh.repo}/issues/{issue}/comments", {"body": text + FOOTER})


def report_nightly(gh: GitHub, issue: int, ok: bool, run_url: str) -> None:
    _comment(gh, issue, f"Nightly e2e: {'pass' if ok else 'fail'} - {run_url}")
    if not ok:
        file_issue(
            gh,
            "Nightly e2e failing",
            f"The nightly e2e run failed: {run_url}",
            ["bug", "area:harness", "agent-filed"],
            "Backlog",
        )


def _announce_ready(gh: GitHub, issue: int) -> None:
    comments = list(gh.paginate(f"/repos/{gh.repo}/issues/{issue}/comments"))
    if comments and READY in (comments[-1].get("body") or ""):
        return  # the latest comment already says so; avoid a weekly repeat
    _comment(gh, issue, READY)


def _bool(text: str) -> bool:
    if text not in ("true", "false"):
        raise argparse.ArgumentTypeError("expected true or false")
    return text == "true"


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="tools.gh.trackers")
    sub = parser.add_subparsers(dest="cmd", required=True)
    night = sub.add_parser("nightly")
    night.add_argument("--issue", type=int, required=True)
    night.add_argument("--ok", type=_bool, required=True)
    sub.add_parser("ready")
    args = parser.parse_args(argv)
    gh = GitHub.from_env()
    if args.cmd == "nightly":
        server = os.environ.get("GITHUB_SERVER_URL", "https://github.com")
        url = f"{server}/{gh.repo}/actions/runs/{os.environ.get('GITHUB_RUN_ID', '0')}"
        report_nightly(gh, args.issue, args.ok, url)
    else:
        for n in ready_trackers(gh):
            _announce_ready(gh, n)
    return 0


if __name__ == "__main__":
    sys.exit(main())
