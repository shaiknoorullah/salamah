"""GitHub event handlers: issue triage, PR metadata, hygiene scan and link rules."""

import argparse
import json
import os
import re
import subprocess
import sys
import tempfile
import urllib.parse
from collections.abc import Callable, Mapping, Sequence
from pathlib import Path

from tools import taxonomy
from tools.gh import rules, sync
from tools.gh.api import GitHub
from tools.hygiene.scan import Finding, load_denylist, redact, scan_diff, scan_text
from tools.taxonomy import Taxonomy

FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
_PNG_STATUS = {"added", "modified", "renamed", "copied"}


def _names(items: Sequence[Mapping]) -> set[str]:
    return {i["name"] for i in items}


def _add_labels(gh: GitHub, number: int, have: set[str], want: Sequence[str]) -> None:
    missing = [lb for lb in want if lb not in have]
    if missing:
        gh.request("POST", f"/repos/{gh.repo}/issues/{number}/labels", {"labels": missing})


def on_issue(gh: GitHub, issue: Mapping, tax: Taxonomy, deny: Sequence[re.Pattern[str]]) -> None:
    n, have = issue["number"], _names(issue.get("labels", []))
    _add_labels(gh, n, have, rules.form_labels(issue.get("body") or "", tax))
    if issue.get("milestone") is None:
        for m in gh.paginate(f"/repos/{gh.repo}/milestones?state=open"):
            if m["title"] == "Backlog":
                gh.request("PATCH", f"/repos/{gh.repo}/issues/{n}", {"milestone": m["number"]})
                break
    findings = scan_text(issue.get("title") or "", "title", deny)
    findings += scan_text(issue.get("body") or "", "body", deny)
    # Skip when already flagged so edits do not repeat the comment.
    if findings and "needs-human" not in have:
        _add_labels(gh, n, have, ["needs-human"])
        lines = "\n".join(f"{f.source}:{f.line}: {f.rule}" for f in findings)
        body = f"Possible private content found; edit the issue to remove it:\n\n{lines}{FOOTER}"
        gh.request("POST", f"/repos/{gh.repo}/issues/{n}/comments", {"body": body})


def on_pr_meta(gh: GitHub, pr: Mapping, tax: Taxonomy) -> None:
    ref = rules.find_issue_ref(pr.get("body") or "")
    if ref is None:
        return
    issue = gh.request("GET", f"/repos/{gh.repo}/issues/{ref[1]}")
    n = pr["number"]
    _add_labels(gh, n, _names(pr.get("labels", [])), [lb["name"] for lb in issue["labels"]])
    if pr.get("milestone") is None and issue.get("milestone"):
        mile = issue["milestone"]["number"]
        gh.request("PATCH", f"/repos/{gh.repo}/issues/{n}", {"milestone": mile})


def _run(cmd: list[str]) -> str:
    try:
        done = subprocess.run(cmd, capture_output=True, text=True, timeout=60, check=True)
    except (OSError, subprocess.SubprocessError) as e:
        print(f"warning: {cmd[0]} failed: {type(e).__name__}", file=sys.stderr)
        return ""
    return done.stdout


def changed_pngs(gh: GitHub, pr: Mapping) -> list[str]:
    """Paths of PNG files the PR adds or changes."""
    return [
        f["filename"]
        for f in gh.paginate(f"/repos/{gh.repo}/pulls/{pr['number']}/files")
        if f.get("status") in _PNG_STATUS and f["filename"].lower().endswith(".png")
    ]


def ocr_pngs(gh: GitHub, pr: Mapping, run: Callable[[list[str]], str]) -> list[tuple[str, str]]:
    out: list[tuple[str, str]] = []
    for path in changed_pngs(gh, pr):
        url = f"/repos/{gh.repo}/contents/{urllib.parse.quote(path)}?ref={pr['head']['sha']}"
        data = gh.request_bytes(url)
        with tempfile.NamedTemporaryFile(suffix=".png") as tmp:
            tmp.write(data)
            tmp.flush()
            out.append((path, run(["tesseract", tmp.name, "stdout"])))
    return out


def on_pr_scan(
    gh: GitHub, pr: Mapping, deny: Sequence[re.Pattern[str]], ocr: Sequence[tuple[str, str]]
) -> list[Finding]:
    n = pr["number"]
    findings = scan_text(pr.get("title") or "", "title", deny)
    findings += scan_text(pr.get("body") or "", "body", deny)
    findings += scan_text(pr.get("head", {}).get("ref") or "", "branch", deny)
    for c in gh.paginate(f"/repos/{gh.repo}/pulls/{n}/commits"):
        findings += scan_text(c["commit"]["message"], f"commit {c['sha'][:7]}", deny)
    diff = gh.request("GET", f"/repos/{gh.repo}/pulls/{n}", accept="application/vnd.github.diff")
    findings += scan_diff(diff or "", deny)
    for f in gh.paginate(f"/repos/{gh.repo}/pulls/{n}/files"):
        hits = scan_text(f["filename"], f["filename"], deny)
        findings += redact([h for h in hits if h.rule.startswith("denylist:")][:1], deny)
    for path, text in ocr:
        findings += redact(scan_text(text, f"{path} (ocr)", deny), deny)
    return findings


def post_hygiene_status(gh: GitHub, sha: str, findings: Sequence[Finding]) -> None:
    if findings:
        ids = ", ".join(sorted({f.rule for f in findings}))
        state, desc = "failure", f"{len(findings)} findings: {ids}"[:140]
    else:
        state, desc = "success", "clean"
    gh.request(
        "POST",
        f"/repos/{gh.repo}/statuses/{sha}",
        {"state": state, "context": "hygiene", "description": desc},
    )


def on_pr_rules(gh: GitHub, pr_number: int, tax: Taxonomy) -> list[str]:
    pr = gh.request("GET", f"/repos/{gh.repo}/pulls/{pr_number}")
    errors = rules.check_title(pr["title"], tax)
    ref = rules.find_issue_ref(pr.get("body") or "")
    if ref is None:
        errors.append("PR body needs '## Issue' with 'Closes #N' or 'Part of #N'")
    else:
        errors += rules.check_branch(pr["head"]["ref"], ref[1], tax)
        errors += rules.check_issue(gh.request("GET", f"/repos/{gh.repo}/issues/{ref[1]}"), tax)
        commits = list(gh.paginate(f"/repos/{gh.repo}/pulls/{pr_number}/commits"))
        errors += rules.check_commits(commits, ref[1], tax)
    files = [f["filename"] for f in gh.paginate(f"/repos/{gh.repo}/pulls/{pr_number}/files")]
    return errors + rules.check_goldens(files, [lb["name"] for lb in pr.get("labels", [])])


def _number(key: str) -> int:
    return json.loads(Path(os.environ["GITHUB_EVENT_PATH"]).read_text())[key]["number"]


def _denylist() -> list[re.Pattern[str]] | None:
    return load_denylist(os.environ, Path.home() / ".config/salamah/denylist")


def _scan(gh: GitHub, require: bool) -> int:
    pr = gh.request("GET", f"/repos/{gh.repo}/pulls/{_number('pull_request')}")
    deny = _denylist()
    if deny is None and require:
        print("error: no denylist configured", file=sys.stderr)
        post_hygiene_status_msg(gh, pr["head"]["sha"], "no denylist configured")
        return 2
    path = Path(os.environ.get("OCR_JSON", "ocr.json"))
    if path.is_file():
        ocr = [tuple(p) for p in json.loads(path.read_text())]
    else:
        print(f"note: {path} not found; no OCR text", file=sys.stderr)
        ocr = []
    findings = on_pr_scan(gh, pr, deny or [], ocr)
    for f in findings:
        print(f"{f.source}:{f.line}: {f.rule}")
    post_hygiene_status(gh, pr["head"]["sha"], findings)
    return 1 if findings else 0


def post_hygiene_status_msg(gh: GitHub, sha: str, message: str) -> None:
    body = {"state": "failure", "context": "hygiene", "description": message}
    gh.request("POST", f"/repos/{gh.repo}/statuses/{sha}", body)


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="tools.gh.events")
    ap.add_argument(
        "cmd", choices=["issue", "pr-meta", "pr-has-png", "pr-ocr", "pr-scan", "pr-rules", "sync"]
    )
    ap.add_argument("--require-denylist", action="store_true")
    args = ap.parse_args(argv)
    if args.cmd == "sync":
        return sync.main([])
    gh, tax = GitHub.from_env(), taxonomy.load()
    if args.cmd == "issue":
        deny = _denylist()
        if deny is None:
            print("warning: no denylist; built-in rules only", file=sys.stderr)
        issue = gh.request("GET", f"/repos/{gh.repo}/issues/{_number('issue')}")
        on_issue(gh, issue, tax, deny or [])
        return 0
    if args.cmd == "pr-scan":
        return _scan(gh, args.require_denylist)
    n = _number("pull_request")
    if args.cmd == "pr-rules":
        errors = on_pr_rules(gh, n, tax)
        for e in errors:
            print(e)
        return 1 if errors else 0
    pr = gh.request("GET", f"/repos/{gh.repo}/pulls/{n}")
    if args.cmd == "pr-has-png":
        line = f"pngs={'true' if changed_pngs(gh, pr) else 'false'}\n"
        target = os.environ.get("GITHUB_OUTPUT")
        if target:
            with open(target, "a", encoding="utf-8") as fh:
                fh.write(line)
        else:
            print(line, end="")
        return 0
    if args.cmd == "pr-meta":
        on_pr_meta(gh, pr, tax)
    else:
        print(json.dumps(ocr_pngs(gh, pr, _run)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
