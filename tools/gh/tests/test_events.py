def _event(tmp_path, monkeypatch, key, n):
    p = tmp_path / "ev.json"
    p.write_text(json.dumps({key: {"number": n}}))
    monkeypatch.setenv("GITHUB_EVENT_PATH", str(p))


def test_main_reads_event_file(tmp_path, monkeypatch):
    _event(tmp_path, monkeypatch, "issue", 3)
    gh = FakeGitHub(
        {
            ("GET", "/repos/o/r/issues/3"): {
                "number": 3,
                "title": "t",
                "body": "",
                "labels": [],
                "milestone": {"number": 1},
            }
        }
    )
    monkeypatch.setattr(events.GitHub, "from_env", classmethod(lambda cls: gh))
    monkeypatch.delenv("SALAMAH_DENYLIST", raising=False)
    monkeypatch.setenv("HOME", str(tmp_path))
    assert events.main(["issue"]) == 0
    assert ("GET", "/repos/o/r/issues/3", None) in gh.calls


