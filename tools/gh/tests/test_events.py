def test_post_hygiene_status_never_holds_term():
    gh = FakeGitHub()
    events.post_hygiene_status(
        gh, "abc", [Finding(TERM, 1, "denylist:1"), Finding("x", 2, "email")]
    )
    method, path, body = gh.calls[0]
    assert (method, path) == ("POST", "/repos/o/r/statuses/abc")
    assert body["context"] == "hygiene" and body["state"] == "failure"
    assert body["description"] == "2 findings: denylist:1, email"
    assert TERM not in json.dumps(gh.calls)
    events.post_hygiene_status(gh, "abc", [])
    assert gh.calls[1][2]["state"] == "success" and gh.calls[1][2]["description"] == "clean"


