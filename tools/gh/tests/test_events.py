def test_on_issue_flags_private_terms():
    gh = FakeGitHub()
    issue = {
        "number": 3,
        "title": "t",
        "body": f"ok\nsee {TERM} here",
        "labels": [],
        "milestone": {"number": 9},
    }
    events.on_issue(gh, issue, TAX, DENY)
    assert gh.posts("/issues/3/labels")[0][2] == {"labels": ["needs-human"]}
    comment = gh.posts("/issues/3/comments")[0][2]["body"]
    assert "body:2: denylist:1" in comment and comment.endswith(FOOT)
    assert TERM not in json.dumps(gh.calls)


