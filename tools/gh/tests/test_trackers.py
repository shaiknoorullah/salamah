import pytest

from tools.gh import trackers

FOOT = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
OPEN = "/repos/o/r/issues?state=open&labels=agent-filed"
MILES = "/repos/o/r/milestones?state=open"


class FakeGitHub:
    repo = "o/r"

    def __init__(self, responses=None, pages=None):
        self.calls = []
        self.responses = responses or {}
        self.pages = pages or {}

    def request(self, method, path, body=None, **kw):
        self.calls.append((method, path, body))
        return self.responses.get((method, path))

    def paginate(self, path):
        self.calls.append(("PAGE", path, None))
        return iter(self.pages.get(path, []))

    def posts(self, suffix):
        return [c for c in self.calls if c[0] == "POST" and c[1].endswith(suffix)]


def test_find_milestone_and_missing():
    gh = FakeGitHub(pages={MILES: [{"number": 4, "title": "Backlog"}]})
    assert trackers.find_milestone(gh, "Backlog") == 4
    with pytest.raises(LookupError):
        trackers.find_milestone(gh, "Nope")


def test_file_issue_dedupes():
    pages = {OPEN: [{"number": 3, "title": "PR", "pull_request": {}}, {"number": 7, "title": "t"}]}
    gh = FakeGitHub(pages=pages)
    assert trackers.file_issue(gh, "t", "b", ["x"], "Backlog") == 7
    assert not [c for c in gh.calls if c[0] == "POST"]
    pages = {OPEN: [{"number": 3, "title": "t", "pull_request": {}}]}
    gh = FakeGitHub({("POST", "/repos/o/r/issues"): {"number": 9}}, pages | {MILES: []})
    with pytest.raises(LookupError):
        trackers.file_issue(gh, "t", "b", ["x"], "Backlog")


def test_file_issue_sets_labels_and_milestone():
    gh = FakeGitHub(
        {("POST", "/repos/o/r/issues"): {"number": 12}},
        {MILES: [{"number": 4, "title": "Backlog"}]},
    )
    assert trackers.file_issue(gh, "t", "body", ["chore", "agent-filed"], "Backlog") == 12
    (post,) = gh.posts("/issues")
    assert post[2] == {
        "title": "t",
        "body": "body" + FOOT,
        "labels": ["chore", "agent-filed"],
        "milestone": 4,
    }


def test_ready_trackers():
    gh = FakeGitHub(
        {
            ("GET", "/repos/o/r/issues/1/sub_issues"): [{"state": "closed"}, {"state": "closed"}],
            ("GET", "/repos/o/r/issues/2/sub_issues"): [{"state": "closed"}, {"state": "open"}],
            ("GET", "/repos/o/r/issues/3/sub_issues"): [],
        },
        {
            "/repos/o/r/issues?state=open": [
                {"number": 1},
                {"number": 2},
                {"number": 3},
                {"number": 4, "pull_request": {}},
            ]
        },
    )
    assert trackers.ready_trackers(gh) == [1]
    assert ("GET", "/repos/o/r/issues/4/sub_issues", None) not in gh.calls


def test_report_nightly_body():
    gh = FakeGitHub()
    trackers.report_nightly(gh, 11, True, "http://run/1")
    (post,) = gh.posts("/issues/11/comments")
    assert post[2] == {"body": "Nightly e2e: pass - http://run/1" + FOOT}
    assert len(gh.calls) == 1


def test_report_nightly_fail_files_issue():
    gh = FakeGitHub(
        {("POST", "/repos/o/r/issues"): {"number": 20}},
        {MILES: [{"number": 4, "title": "Backlog"}]},
    )
    trackers.report_nightly(gh, 11, False, "http://run/2")
    assert gh.posts("/issues/11/comments")[0][2]["body"].startswith("Nightly e2e: fail - ")
    filed = gh.posts("/repos/o/r/issues")[0][2]
    assert filed["title"] == "Nightly e2e failing"
    assert filed["labels"] == ["bug", "area:harness", "agent-filed"] and filed["milestone"] == 4
    assert "http://run/2" in filed["body"]


def test_main_nightly_parses_ok_strictly(monkeypatch):
    gh = FakeGitHub()
    monkeypatch.setattr(trackers.GitHub, "from_env", classmethod(lambda cls: gh))
    monkeypatch.setenv("GITHUB_SERVER_URL", "http://s")
    monkeypatch.setenv("GITHUB_RUN_ID", "5")
    assert trackers.main(["nightly", "--issue", "11", "--ok", "true"]) == 0
    assert "pass - http://s/o/r/actions/runs/5" in gh.calls[0][2]["body"]
    with pytest.raises(SystemExit):
        trackers.main(["nightly", "--issue", "11", "--ok", "yes"])


def test_main_ready_skips_duplicates(monkeypatch):
    gh = FakeGitHub(
        {
            ("GET", "/repos/o/r/issues/1/sub_issues"): [{"state": "closed"}],
            ("GET", "/repos/o/r/issues/2/sub_issues"): [{"state": "closed"}],
        },
        {
            "/repos/o/r/issues?state=open": [{"number": 1}, {"number": 2}],
            "/repos/o/r/issues/1/comments": [{"body": "All sub-issues closed" + FOOT}],
            "/repos/o/r/issues/2/comments": [{"body": "hi"}],
        },
    )
    monkeypatch.setattr(trackers.GitHub, "from_env", classmethod(lambda cls: gh))
    assert trackers.main(["ready"]) == 0
    (post,) = gh.posts("/comments")
    assert post[1] == "/repos/o/r/issues/2/comments"
    assert post[2] == {"body": "All sub-issues closed" + FOOT}
